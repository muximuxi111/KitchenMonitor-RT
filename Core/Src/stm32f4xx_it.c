void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size)
{
    if(huart == &huart3)
    {		//只接收小于sizeof(USART3_RxBuff)1024大小的数据
        /* 先交给 wifi.c 存进它自己的环形缓冲（这里只入队，不解析，很快返回） */
        Wifi_RxIsr((const uint8_t *)USART3_RxBuff, Size);

				if(Size < sizeof(USART3_RxBuff))
        {
            USART3_RxBuff[Size] = '\0';
        }
        HAL_UARTEx_ReceiveToIdle_IT(&huart3, USART3_RxBuff, 1024);
    }
}

void HAL_UART_TxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart == &huart3)
    {
        /* 发送完成，重新开启接收中断（因为发送期间接收被停了） */
        HAL_UARTEx_ReceiveToIdle_IT(&huart3, USART3_RxBuff, 1024);
    }
}

